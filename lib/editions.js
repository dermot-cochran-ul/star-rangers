// An untracked, gitignored editions.local.json in the repo root, for anyone
// hosting this site independently. Exactly the pattern giscus.local.json
// already establishes (see src/_data/giscus.js), and for the same reason:
// registering your own domain should not require editing a tracked engine file,
// because that means maintaining a fork and re-resolving a conflict on every
// upstream merge. Template: sample-editions.local.json.
//
// Shape: { "editions": [ { "id": "...", "domains": [...], ...overrides } ] }
//
// An entry whose id matches one below OVERRIDES it (merged over, field by
// field); a new id is added. So an independent host can either re-point an
// existing edition at their own domain or declare their own outright.
//
// The canon rule still binds a local file completely - there is no field here
// that can add lore, and that is deliberate. It means an independent host
// cannot publish their own material as this story's canon even by accident,
// which protects them as much as it protects the record.
const LOCAL_CONFIG_PATH = path.join(__dirname, "..", "editions.local.json");

let localCache; // undefined = not yet read, null = absent

function loadLocalEditions() {
  if (localCache !== undefined) return localCache;

  let raw;
  try {
    raw = fs.readFileSync(LOCAL_CONFIG_PATH, "utf8");
  } catch (err) {
    if (err.code === "ENOENT") { localCache = null; return localCache; }
    throw err;
  }

  let parsed;
  try {
    parsed = JSON.parse(raw);
  } catch (err) {
    throw new Error(`lib/editions.js: editions.local.json is not valid JSON - ${err.message}`);
  }
  const list = parsed && parsed.editions;
  if (!Array.isArray(list)) {
    throw new Error(
      "lib/editions.js: editions.local.json must be { \"editions\": [ ... ] }. " +
      "See sample-editions.local.json for the expected shape."
    );
  }
  for (const e of list) {
    if (!e || typeof e.id !== "string" || !e.id.trim()) {
      throw new Error("lib/editions.js: every entry in editions.local.json needs a non-empty string `id`.");
    }
  }
  localCache = list;
  return localCache;
}

/**
 * The tracked registry with any editions.local.json entries merged in.
 * @returns {object[]} edition records (not yet merged over DEFAULT_EDITION)
 */
function allEditions() {
  const local = loadLocalEditions();
  if (!local || !local.length) return EDITIONS;

  const byId = new Map(EDITIONS.map((e) => [e.id, e]));
  for (const entry of local) {
    const id = entry.id.trim().toLowerCase();
    byId.set(id, { ...(byId.get(id) || {}), ...entry, id });
  }
  return [...byId.values()];
}

/**
 * Merge an edition over DEFAULT_EDITION so callers always get a complete
 * record and an entry only has to declare what it changes. Shallow by design:
 * `themeAudio` is replaced wholesale rather than merged key-by-key, because a
 * half-overridden audio player (new label, old file) is never what anyone
 * means.
 *
 * @param {string} id
 * @returns {object} complete edition record; DEFAULT_EDITION for an unknown id
 */
function editionFor(id) {
  const wanted = String(id || "").trim().toLowerCase();
  const found = allEditions().find((e) => e.id === wanted);
  return found ? { ...DEFAULT_EDITION, ...found } : { ...DEFAULT_EDITION };
}

/**
 * Look an edition up by the domain it serves.
 *
 * Matching is on the bare host, case-insensitively, with any scheme, `www.`,
 * port, path and trailing slash stripped first - so "https://Church-Space.site/"
 * and "church-space.site" are the same domain. A path-bearing entry (the
 * GitHub Pages one, "dermot-r-cochran.github.io/star-rangers") is matched on
 * its host part too, since a host cannot serve two editions.
 *
 * Returns null rather than DEFAULT_EDITION on no match, so a caller can tell
 * "this domain is registered as the default edition" apart from "this domain is
 * not registered at all" - the deploy log says which, and a silent default is
 * how a domain ends up quietly serving the wrong thing.
 *
 * @param {string} domain
 * @returns {object|null} complete edition record, or null if unregistered
 */
function editionForDomain(domain) {
  const host = bareHost(domain);
  if (!host) return null;
  const all = [DEFAULT_EDITION, ...allEditions()];
  const found = all.find((e) => (e.domains || []).some((d) => bareHost(d) === host));
  return found ? { ...DEFAULT_EDITION, ...found } : null;
}

function bareHost(value) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/^[a-z]+:\/\//, "")
    .replace(/^www\./, "")
    .split("/")[0]
    .split(":")[0];
}

/**
 * Resolve the edition for this build from the environment.
 *
 * EDITION wins; THEME is the migration fallback (see MIGRATION SAFETY above);
 * an unset or unrecognised value yields DEFAULT_EDITION. Deliberately does NOT
 * throw on an unknown id, unlike GISCUS_PROFILE in src/_data/giscus.js - a
 * wrong giscus profile silently attaches reader comments to the wrong repo,
 * which is unrecoverable, whereas a wrong edition id costs a domain its
 * tagline and is obvious on the homepage.
 *
 * @returns {object} complete edition record
 */
function getEdition() {
  return editionFor(process.env.EDITION || process.env.THEME);
}

/**
 * Fail the build on a malformed registry. Called from .eleventy.js at config
 * time, so a mistake here stops the build instead of shipping a broken page.
 *
 * This exists because moving copy out of src/ cost some automatic checking,
 * and the loss should be paid back rather than absorbed. Two specifics:
 *
 *   - `themeAudio.file` used to appear in base.njk as a literal audio src
 *     under /star-rangers/audio/, which scripts/check-internal-links.js
 *     verified. It is now a bare filename assembled by a template, so that
 *     script skips it as a templated href - a typo would ship a player
 *     pointing at nothing. Checked against src/audio/ here instead.
 *     (Deliberately described rather than quoted as a path: that script now
 *     scans this file, and a made-up example URL in a comment would fail it -
 *     as one did while this was being written.)
 *   - `heroSubtitle` links ARE still covered: check-internal-links.js now
 *     scans this file by name (see its EXTRA_FILES).
 *
 * Duplicate ids are checked too: EDITIONS_BY_ID would silently keep the last
 * one, the same quiet-wrong-answer failure validate-content.js guards against
 * for chapter comment_id collisions.
 *
 * @param {string} audioDir absolute path to the directory holding audio files
 * @throws {Error} on a duplicate id, or an audio file that isn't there
 */
function validateEditions({ audioDir, cssDir }) {
  const all = [DEFAULT_EDITION, ...allEditions()];

  const seenIds = new Set();
  for (const e of all) {
    if (seenIds.has(e.id)) {
      throw new Error(`lib/editions.js: duplicate edition id "${e.id}" - only one of them would ever be used.`);
    }
    seenIds.add(e.id);
  }

  // A domain claimed by two editions is the worst failure mode this file has:
  // resolution would pick whichever came first and the other domain would
  // quietly serve the wrong branding forever. Cheap to rule out here.
  const seenDomains = new Map();
  for (const e of all) {
    for (const d of e.domains || []) {
      const host = bareHost(d);
      if (seenDomains.has(host)) {
        throw new Error(
          `lib/editions.js: domain "${host}" is claimed by both "${seenDomains.get(host)}" and "${e.id}".`
        );
      }
      seenDomains.set(host, e.id);
    }
  }

  for (const e of all) {
    const file = (e.themeAudio || DEFAULT_EDITION.themeAudio).file;
    if (!fs.existsSync(path.join(audioDir, file))) {
      throw new Error(
        `lib/editions.js: edition "${e.id}" names themeAudio.file "${file}", which is not in ${audioDir}.`
      );
    }
    // A typo'd theme name is not otherwise loud: cpanel-deploy.sh checks the
    // file exists and silently keeps main.css when it doesn't, so the domain
    // deploys looking unbranded rather than failing.
    const theme = e.theme || DEFAULT_EDITION.theme;
    if (cssDir && theme !== "default" && !fs.existsSync(path.join(cssDir, `theme-${theme}.css`))) {
      throw new Error(
        `lib/editions.js: edition "${e.id}" names theme "${theme}", but ${path.join(cssDir, `theme-${theme}.css`)} does not exist.`
      );
    }
  }
}

