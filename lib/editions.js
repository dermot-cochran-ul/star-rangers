// Canonical registry of per-domain EDITIONS - the copy and flourishes that
// differ between the production domains this one repo deploys to.
//
// "Edition" is the site's own existing word for a per-domain build, not a new
// coinage: src/_includes/excluded.njk has told readers "Not included in this
// edition" since narrowing was introduced. This file makes that concept
// first-class on the authoring side too.
//
// WHY THIS EXISTS, AND WHAT IT IS NOT
//
// Three mechanisms already vary a build per domain, and this is deliberately
// none of them:
//
//   - deploy.conf's CHARACTERS/TOPICS/THREADS (lib/content-filter.js) is
//     SUBTRACTIVE: it narrows an otherwise-full site down to a subset. It can
//     hide a page; it cannot give a domain a sentence of its own.
//   - THEME (src/css/theme-*.css, generated by scripts/generate-themes.js) is
//     COSMETIC: a palette swap, byte-identical to main.css otherwise.
//   - CUSTOM_LORE_FILE / CUSTOM_CSS_FILE (scripts/cpanel-deploy.sh) are
//     ADDITIVE but live OUTSIDE the repo, on the cPanel account. That is the
//     right shape for the case they were built for - content a third-party
//     clone operator owns, which Dermot cannot license into a CC BY-NC-ND
//     repo - and the wrong shape for his own per-domain copy, which wants to
//     be versioned, reviewable, checkable by `npm test` and the link/related
//     scripts, and inside the licence structure CONTENT-LICENSE.md describes.
//
// This registry is the fourth thing: additive, in-repo, per-domain copy.
//
// THE GOVERNING RULE: CANON IS CENTRALISED, VARIANTS ARE NON-CANONICAL
//
// Settled 2026-07-30, and it is a constraint on this file rather than a note
// about it. **Nothing an edition carries may assert a fact about the world.**
// Canon - src/seasons/, src/lore/, src/glossary/ - is identical on every
// domain, and every field here is framing: a tagline, which characters to put
// in a slideshow, which audio to offer. Reword the pitch, never the record.
//
// The test for a proposed field is not "is this nice for that domain?" but
// "could two domains now disagree about something true?" If yes, it does not
// belong here, and it does not belong anywhere else either.
//
// Note that this rule is what makes the multi-domain deployment coherent
// rather than merely convenient. Filtering can only ever SUBTRACT, so a
// narrowed clone shows a subset of one record and never a contradiction of it.
// If an edition could add lore, that guarantee would be gone: two domains
// could describe the same institution differently, and the archive would stop
// being a single record with several doors into it. That is also precisely why
// deploy.conf's CUSTOM_LORE_FILE is deprecated (2026-07-30) - injecting a page
// into src/lore/ per clone was the one mechanism that could produce
// per-domain canon. There is no replacement for it, on purpose.
//
// Two consequences worth stating, since both will come up:
//
//   - A domain that genuinely needs a page of its own gets a NON-canonical
//     one - an "about this edition" note, framing, front-of-house copy - not a
//     lore entry. If the material is worth being true, it is worth being true
//     everywhere, and it belongs in src/lore/ on every domain.
//   - The four canon statuses are unaffected and no fifth is being added.
//     An edition is not canon, not codex (which is in-universe authorship),
//     not an overlay (a declared reading of the same events), and not
//     chartered (another hand's work). It is the shop window, not the archive.
//
// WHY NOT KEEP USING `theme` FOR THIS
//
// Because `theme` was already doing it, and was already at its limit. The
// branches this file replaces were spelled `{% if theme == "fellowship" %}`,
// which conflates palette with identity and fails in three ways as domains
// diverge:
//
//   1. Several domains share one palette. sample-deploy.conf has four `fol*`
//      entries on THEME=fellowship and two `churchspace*` entries on
//      THEME=church-space - six domains, two identities. The moment one of
//      those four wants its own tagline, `theme` cannot express it.
//   2. A domain wanting a general-purpose palette (light, sepia,
//      high-contrast, solarized) plus its own copy had no way to ask: picking
//      the palette silently picked the copy too.
//   3. Copy organised by `theme` lives wherever the template is, so ONE
//      domain's identity scatters across src/index.md, base.njk and anything
//      added later. Edit points grow as domains x templates. This file
//      inverts that: one entry per edition, listing what that edition
//      overrides, however many templates read it.
//
// The two axes are now independent. `EDITION=folspace THEME=fellowship` is a
// sentence you can write.
//
// MIGRATION SAFETY - read before renaming an id
//
// getEdition() falls back to THEME when EDITION is unset, and every id below
// that names an existing look is spelled exactly as that theme is. deploy.conf
// is UNTRACKED and lives on the cPanel account, so the live configs cannot be
// updated from here - a live domain setting only THEME=fellowship therefore
// keeps rendering the fellowship edition with no edit at all. Renaming an id
// below, or dropping the THEME fallback, silently reverts those domains to the
// default copy. Add `EDITION=` to a deploy.conf first; retire the fallback
// only once every live clone sets it.
//
// ADDING AN EDITION
//
// Add an entry with an `id` and only the fields it actually overrides -
// editionFor() merges over DEFAULT_EDITION, so a domain that wants one new
// tagline writes one field, not a full record.
//
// `domains` IS LOAD-BEARING (since 2026-07-30). scripts/resolve-edition.js
// looks a domain up here so scripts/cpanel-deploy.sh can fill in THEME,
// THREADS, CHARACTERS, TOPICS, SITE_NAME, SITE_TITLE, COMMENTS_ENABLED and
// GISCUS_PROFILE for any key that clone's deploy.conf leaves unset - taking a
// minimum viable deploy.conf down to CPANEL_USER and DOMAIN.
//
// **deploy.conf still wins wherever it sets a value.** That is not only
// migration cover, it is the honest ordering: the values below for the alt
// domains are inferred from sample-deploy.conf's commented examples, since the
// real deploy.conf is untracked and cannot be read from here. The deploy log
// prints the provenance of every resolved key for exactly this reason - check
// it on the first deploy after this lands, and correct the entries below
// against what those domains actually set.
//
// WHY THIS DOES NOT WEAKEN PRIVATE-THREAD OPT-IN
//
// `threads` below can name `church-space`, a private thread, which
// lib/content-filter.js otherwise hides on every build. That is still explicit
// opt-in by naming, and naming it HERE is stronger than naming it in
// deploy.conf: this file is tracked, reviewed in a pull request, and versioned,
// where an untracked file on a cPanel account is none of those. What must never
// happen is opt-in inferred from the SHAPE of a domain string - "the host
// starts with church-space, so switch the thread on". That is pattern-matching
// masquerading as a decision. A registry entry is a decision.

